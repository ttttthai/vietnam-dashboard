"""Map every tab's story for the Narrator agent: chapters, headlines, notes and charts with the ids a film scene can target.

Opens each tab in a headless browser (server on --port, default 8002), reads the rendered story and writes
data/research/story_map.json (and a short summary to stdout). A film scene in data/narration.json names a tab,
a chapter id ("chap") and optionally a chart/element selector ("target") taken from this map.

Usage:
  python3 tools/qa/story_map.py                 # all tabs, Vietnamese
  python3 tools/qa/story_map.py --lang en       # English text
  python3 tools/qa/story_map.py --tab econ      # one tab
"""
import argparse, json, os, sys, time, urllib.request

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
CHROME = '/opt/pw-browsers/chromium-1194/chrome-linux/chrome'
TABS = ['party', 'social', 'econ', 'money', 'banks', 'invest', 'sim']

JS = r"""
(() => {
  const txt = e => e ? e.textContent.replace(/\s+/g, ' ').trim() : '';
  const panel = document.querySelector('.panel.active'), root = panel && panel.querySelector('.st-root');
  if (!root || !root._stSub) return null;
  return root._stSub.secs.map((top, i) => {
    const chaps = top.matches('section.st-chap') && !top.querySelector('section.st-chap') ? [top] : [...top.querySelectorAll('section.st-chap')];
    return { subtab: i, subtab_id: top.id, label: txt(document.getElementById(root.id + '-tab-' + i)), chapters: (chaps.length ? chaps : [top]).map(c => ({
      chap: c.id, kicker: txt(c.querySelector('.st-kicker')), headline: txt(c.querySelector('.st-h')), dek: txt(c.querySelector('.st-dek')).slice(0, 400),
      notes: [...c.querySelectorAll('.st-note')].map(txt).map(t => t.slice(0, 300)),
      charts: [...c.querySelectorAll('.st-anim-w, .st-viz[id], .st-waffles[id]')].filter(e => !(e.matches('.st-viz, .st-waffles') && e.closest('.st-anim-w'))).map(e => {
        const v = e.matches('.st-anim-w') ? (e.querySelector('[id]') || e) : e, sv = e.querySelector('svg[aria-label]');
        let cap = '', p = e.previousElementSibling; for (let n = 0; p && n < 4 && !cap; n++, p = p.previousElementSibling) if (p.matches('.st-sub, .st-waf-h, .st-mini-h, .iv-sec')) cap = txt(p);
        return { target: v.id ? '#' + v.id : null, caption: cap || (sv ? sv.getAttribute('aria-label') : ''), timeline: !!(e.querySelector('.st-anim') || (v.id && document.getElementById(v.id + '-ctl'))) };
      }).filter(c => c.target) })) };
  });
})()
"""


def main():
    a = argparse.ArgumentParser(); a.add_argument('--lang', default='vi'); a.add_argument('--tab'); a.add_argument('--port', type=int, default=int(os.environ.get('DASH_PORT', 8002)))
    o = a.parse_args(); base = f'http://127.0.0.1:{o.port}/'
    for _ in range(60):
        try:
            urllib.request.urlopen(base, timeout=5); break
        except Exception: time.sleep(2)
    else: sys.exit(f'server not answering at {base}')
    from playwright.sync_api import sync_playwright
    path = os.path.join(ROOT, 'data', 'research', 'story_map.json' if o.lang == 'vi' else f'story_map_{o.lang}.json')
    out = {'_meta': {'built': time.strftime('%Y-%m-%d'), 'lang': o.lang, 'note': 'Generated by tools/qa/story_map.py; read-only reference for data/narration.json.'}}
    with sync_playwright() as p:
        b = p.chromium.launch(executable_path=CHROME if os.path.exists(CHROME) else None)
        pg = b.new_page(viewport={'width': 1360, 'height': 1000}); pg.goto(f'{base}?lang={o.lang}', wait_until='load')
        pg.wait_for_function("document.querySelector('.tab-btn[data-tab]')", timeout=30000)
        if o.tab and os.path.exists(path):   # one tab: update it inside the existing map, keep the others
            old = json.load(open(path, encoding='utf-8')); out = {**old, '_meta': out['_meta']}
        for t in ([o.tab] if o.tab else TABS):
            pg.evaluate(f"document.querySelector('.tab-btn[data-tab=\"{t}\"]').click()"); pg.wait_for_timeout(2500)
            out[t] = pg.evaluate(JS)
            n = sum(len(s['chapters']) for s in out[t] or []); c = sum(len(ch['charts']) for s in out[t] or [] for ch in s['chapters'])
            print(f'{t:7s} {len(out[t] or [])} sub-tabs, {n} chapters, {c} charts')
        b.close()
    json.dump(out, open(path, 'w', encoding='utf-8'), ensure_ascii=False, indent=1); print('wrote', os.path.relpath(path, ROOT))


main()
