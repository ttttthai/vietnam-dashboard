"""Embed ECONFLOW (GDP by expenditure, balance of payments, tourism, remittances, labour export, budget, investment) into the dashboard."""
import json, os
D = os.path.dirname(os.path.abspath(__file__))
E = json.load(open(os.path.join(D, 'econ_flows.json')))
keep = lambda o, ks: {k: o[k] for k in ks if k in o}
EF = {
    'gdp': keep(E['gdp_exp'], ['years', 'C', 'G', 'I', 'GFCF', 'inventories', 'X', 'M', 'net_exports', 'discrepancy', 'GDP', 'pct_gdp', 'growth_real_pct', 'basis']),
    'bop': {'years': E['bop']['years'], 's': E['bop']['series'], 'sign': E['bop'].get('sign_convention')},
    'tour': keep(E['tourism'], ['years', 'intl_arrivals_thousand', 'travel_receipts_busd', 'travel_payments_busd', 'vietnamese_outbound_departures_thousand', 'total_tourism_revenue_vnat_trn_vnd']),
    'remit': keep(E['remittances'], ['years', 'national_sbv_busd', 'national_wb_knomad_busd', 'national_wb_projection_busd', 'hcmc_busd']),
    'labour': keep(E['labour_export'], ['years', 'workers_sent', 'remit_statements']),
    'budget': keep(E['budget'], ['years', 'revenue', 'expenditure', 'deficit', 'deficit_pct_gdp', 'basis']),
    'inv': keep(E['invest_by_owner'], ['years', 'total', 'state', 'nonstate', 'fdi', 'growth_9M2026_yoy_pct']),
    'debt': (E['bop'].get('external_debt_service') or {}),
}
js = json.dumps(EF, ensure_ascii=False, separators=(',', ':'))
p = '/Users/hoangthai/CLAUDECODE/VIETNAM DASHBOARD/vietnam_dashboard.html'
s = open(p, encoding='utf-8').read()
start, end = '// ── ECONFLOW data (generated by scratchpad/econ/ec_build.py) ──', '// ── /ECONFLOW data ──'
block = f'{start}\nconst ECONFLOW = {js};\n{end}'
if start in s:
    i = s.index(start); j = s.index(end, i) + len(end); s = s[:i] + block + s[j:]
else:
    anchor = '// ── ECON renderer ──'; assert anchor in s; s = s.replace(anchor, block + '\n' + anchor, 1)
open(p, 'w', encoding='utf-8').write(s)
print('ECONFLOW embedded', round(len(js) / 1024), 'KB')
