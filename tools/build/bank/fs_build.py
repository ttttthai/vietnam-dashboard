"""Build FINSYS (compact data object for the 'Hệ thống tài chính' tab) from the research JSON files and embed it in the dashboard."""
import json, os, re
D = os.path.dirname(os.path.abspath(__file__))
M = json.load(open(os.path.join(D, 'money.json')))
W = json.load(open(os.path.join(D, 'why_rates.json')))
try:
    SBV = json.load(open(os.path.join(D, 'sbv_bs.json')))
except Exception:
    SBV = None

def r(v, n=2):
    return None if v is None else (round(v, n) if isinstance(v, (int, float)) else v)

a = M['annual']; m = M['monthly']; cs = M['credit_by_sector']
ratio = lambda k: [{'d': x['date'], 'v': x['value'], 'u': x.get('url'), 'n': x.get('note')} for x in M['ratios'].get(k, []) if isinstance(x.get('value'), (int, float))]
flows = {}
for f in M['flows']:
    flows.setdefault(f['item'], []).append({'d': f['date'], 'v': f['value'], 'unit': f['unit'], 'u': f.get('url')})

S = W['series']
FS = {
    'asof': '2026-10-05',
    'annual': {k: a.get(k) for k in ['years', 'm2', 'deposits', 'loans_imf_fsi', 'credit', 'credit_growth', 'm2_growth', 'deposit_growth', 'm2_to_gdp_pct_wb', 'private_credit_to_gdp_pct_wb']},
    'monthly': {k: m.get(k) for k in ['months', 'm2_level', 'm2_ytd', 'deposits_level', 'deposits_ytd', 'deposits_residents', 'deposits_econ_orgs', 'credit_level', 'credit_ytd', 'credit_yoy', 'cash_to_m2_pct']},
    'ratios': {k: ratio(k) for k in ['ldr_sbv_tt22_pct', 'short_term_funds_for_mlt_loans_pct', 'npl_onbalance_sbv_pct', 'npl_incl_vamc_and_potential_pct', 'npl_imf_fsi_pct', 'car_imf_fsi_pct', 'car_basel2_banks_tt41_pct', 'roa_sbv_pct', 'roe_sbv_pct', 'roa_imf_fsi_pct', 'roe_imf_fsi_pct', 'nim_listed_banks_pct', 'credit_to_gdp_pct', 'npl_onbalance_excl_5_weak_banks_pct', 'provisions_to_npl_imf_fsi_pct', 'commercial_real_estate_loans_share_imf_fsi_pct', 'total_assets_ci_vnd_bn']},
    'sectors': {'periods': cs['periods'], 'levels': cs['sectors'], 'growth_ytd': cs.get('growth_ytd_pct'), 'unit': cs.get('unit')},
    'flows': flows,
    'why': {'drivers': W['drivers'], 'summary_vi': W.get('summary_vi'), 'summary_en': W.get('summary_en'),
            'series': {k: S[k] for k in ['cof', 'nim', 'casa', 'ldr', 'credit_vs_deposit_growth', 'deposit12m_private_banks_mbs', 'avg_lending_rate_sbv', 'usdvnd_monthly', 'fed_funds_upper', 'dxy_month_end', 'interbank_on_monthly'] if k in S}},
    'sbv': SBV,
    'sources': {'money': M['annual'].get('sources'), 'monthly': M['monthly'].get('sources'), 'sectors': cs.get('sources')},
}
js = json.dumps(FS, ensure_ascii=False, separators=(',', ':'))
p = '/Users/hoangthai/CLAUDECODE/VIETNAM DASHBOARD/vietnam_dashboard.html'
s = open(p, encoding='utf-8').read()
start, end = '// ── FINSYS data (generated by scratchpad/bank/fs_build.py) ──', '// ── /FINSYS data ──'
block = f'{start}\nconst FINSYS = {js};\n{end}'
if start in s:
    i = s.index(start); j = s.index(end, i) + len(end)
    s = s[:i] + block + s[j:]
else:
    anchor = '// ── FINSYS renderer ──'
    assert anchor in s, 'renderer anchor missing'
    s = s.replace(anchor, block + '\n' + anchor, 1)
open(p, 'w', encoding='utf-8').write(s)
print('FINSYS embedded', round(len(js) / 1024), 'KB; sbv:', bool(SBV))
