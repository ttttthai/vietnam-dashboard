"""Embed POLICY (monetary + fiscal registries) into the dashboard."""
import json, os
D = os.path.dirname(os.path.abspath(__file__))
P = {'mon': json.load(open(os.path.join(D, 'monetary.json'))), 'fis': json.load(open(os.path.join(D, 'fiscal.json')))}
js = json.dumps(P, ensure_ascii=False, separators=(',', ':'))
p = '/Users/hoangthai/CLAUDECODE/VIETNAM DASHBOARD/vietnam_dashboard.html'
s = open(p, encoding='utf-8').read()
start, end = '// ── POLICY data (generated by scratchpad/policy/pol_build.py) ──', '// ── /POLICY data ──'
block = f'{start}\nconst POLICY = {js};\n{end}'
if start in s:
    i = s.index(start); j = s.index(end, i) + len(end); s = s[:i] + block + s[j:]
else:
    anchor = '// ── POLICY renderer ──'; assert anchor in s; s = s.replace(anchor, block + '\n' + anchor, 1)
open(p, 'w', encoding='utf-8').write(s)
print('POLICY embedded', round(len(js) / 1024), 'KB')
